#!/usr/bin/env bash
# ==============================================================================
# My Audit Cloud Deployment Script (One-Click Launch)
# مخصص للنشر السحابي الفوري على خوادم ومراكز بيانات سحابية (KSA Cloud / VPS)
# ==============================================================================
set -e

echo "================================================================================"
echo "    بدء إعداد ونشر منظومة ماي أودت السحابية (My Audit Cloud Deployment)        "
echo "================================================================================"

# 1. التحقق من توافر Docker و Docker Compose
if ! command -v docker &> /dev/null; then
    echo "[!] Docker غير مثبت. يرجى تثبيت Docker أولاً: curl -fsSL https://get.docker.com | sh"
    exit 1
fi

echo "[✓] تم التحقق من بيئة Docker بنجاح."

# 2. إنشاء المجلدات السحابية ومجلدات البيانات
mkdir -p data storage logs

# 3. بناء وتشغيل الحاويات السحابية
echo "[*] جاري تشغيل خدمات المنظومة السحابية (FastAPI + PostgreSQL + Redis + MinIO + Nginx)..."
docker compose -f docker-compose.cloud.yml up -d --build

echo "================================================================================"
echo "[✓] تم إطلاق منظومة ماي أودت السحابية بنجاح تام!"
echo "    - رابط لوحة التحكم السحابية: http://localhost (أو عنوان IP الخادم السحابي)"
echo "    - رابط واجهة REST API الموثقة: http://localhost:8000/docs"
echo "    - لوحة تحكم التخزين السحابي MinIO S3: http://localhost:9001"
echo "================================================================================"
